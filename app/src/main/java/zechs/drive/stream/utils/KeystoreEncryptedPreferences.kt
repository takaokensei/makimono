package zechs.drive.stream.utils

import android.content.Context
import android.content.SharedPreferences
import android.os.Build
import android.annotation.TargetApi
import android.security.KeyPairGeneratorSpec
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import org.json.JSONArray
import org.json.JSONObject
import java.nio.charset.StandardCharsets
import java.math.BigInteger
import java.security.KeyStore
import java.security.MessageDigest
import java.security.KeyPair
import java.security.KeyPairGenerator
import java.security.SecureRandom
import java.util.Calendar
import javax.security.auth.x500.X500Principal
import java.util.concurrent.CopyOnWriteArraySet
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec
import javax.crypto.spec.SecretKeySpec

/** Stores the complete preferences payload as AES-GCM ciphertext authenticated to its store name. */
class KeystoreEncryptedPreferences(
    context: Context,
    private val storeName: String
) : SharedPreferences {

    companion object {
        private const val ANDROID_KEY_STORE = "AndroidKeyStore"
        private const val PAYLOAD_KEY = "encrypted_payload_v1"
        private const val KEY_ALIAS_PREFIX = "makimono_prefs_"
        private const val RSA_KEY_SUFFIX = "_rsa_wrap"
        private const val IV_BYTES = 12
        private const val GCM_TAG_BITS = 128
    }

    private val appContext = context.applicationContext
    private val disk = appContext.getSharedPreferences("${storeName}_ciphertext", Context.MODE_PRIVATE)
    private val lock = Any()
    private val listeners = CopyOnWriteArraySet<SharedPreferences.OnSharedPreferenceChangeListener>()
    private var values = readEncryptedPayload()

    private fun keyAlias(): String {
        val digest = MessageDigest.getInstance("SHA-256").digest(storeName.toByteArray(StandardCharsets.UTF_8))
        val suffix = Base64.encodeToString(digest, Base64.URL_SAFE or Base64.NO_WRAP or Base64.NO_PADDING)
        return KEY_ALIAS_PREFIX + suffix.take(32)
    }

    @TargetApi(Build.VERSION_CODES.M)
    private fun secretKey(): SecretKey {
        check(Build.VERSION.SDK_INT >= Build.VERSION_CODES.M) {
            "Android Keystore AES-GCM storage requires Android 6.0 or newer"
        }
        val keyStore = KeyStore.getInstance(ANDROID_KEY_STORE).apply { load(null) }
        val alias = keyAlias()
        (keyStore.getKey(alias, null) as? SecretKey)?.let { return it }
        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEY_STORE)
        generator.init(
            KeyGenParameterSpec.Builder(
                alias,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                .setRandomizedEncryptionRequired(true)
                .build()
        )
        return generator.generateKey()
    }

    /** Android 5.x lacks AES key generation in Android Keystore; wrap a random AES key with a Keystore RSA key there. */
    private fun legacyWrappingKeyPair(): KeyPair {
        val keyStore = KeyStore.getInstance(ANDROID_KEY_STORE).apply { load(null) }
        val alias = keyAlias() + RSA_KEY_SUFFIX
        val certificate = keyStore.getCertificate(alias)
        val privateKey = keyStore.getKey(alias, null) as? java.security.PrivateKey
        if (certificate != null && privateKey != null) return KeyPair(certificate.publicKey, privateKey)

        val start = Calendar.getInstance()
        val end = Calendar.getInstance().apply { add(Calendar.YEAR, 25) }
        val generator = KeyPairGenerator.getInstance("RSA", ANDROID_KEY_STORE)
        generator.initialize(
            KeyPairGeneratorSpec.Builder(appContext)
                .setAlias(alias)
                .setSubject(X500Principal("CN=$alias"))
                .setSerialNumber(BigInteger.ONE)
                .setStartDate(start.time)
                .setEndDate(end.time)
                .build()
        )
        return generator.generateKeyPair()
    }

    private fun crypt(plainText: ByteArray): String {
        val key = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.M) {
            secretKey()
        } else {
            KeyGenerator.getInstance("AES").apply { init(256) }.generateKey()
        }
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        val iv = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.M) {
            // Android Keystore requires a fresh IV to be generated by the cipher when
            // randomized encryption is enabled on the key.
            cipher.init(Cipher.ENCRYPT_MODE, key)
            cipher.iv ?: throw IllegalStateException("Android Keystore did not provide an AES-GCM IV")
        } else {
            ByteArray(IV_BYTES).also(SecureRandom()::nextBytes).also { generatedIv ->
                cipher.init(Cipher.ENCRYPT_MODE, key, GCMParameterSpec(GCM_TAG_BITS, generatedIv))
            }
        }
        require(iv.size == IV_BYTES) { "AES-GCM returned an invalid IV" }
        cipher.updateAAD(storeName.toByteArray(StandardCharsets.UTF_8))
        val encrypted = cipher.doFinal(plainText)
        val flags = Base64.URL_SAFE or Base64.NO_WRAP or Base64.NO_PADDING
        val ivText = Base64.encodeToString(iv, flags)
        val ciphertextText = Base64.encodeToString(encrypted, flags)
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.M) return "v1.$ivText.$ciphertextText"

        val wrapper = Cipher.getInstance("RSA/ECB/PKCS1Padding")
        wrapper.init(Cipher.ENCRYPT_MODE, legacyWrappingKeyPair().public)
        val wrappedKey = Base64.encodeToString(wrapper.doFinal(key.encoded), flags)
        return "rsa1.$wrappedKey.$ivText.$ciphertextText"
    }

    private fun decrypt(encoded: String): ByteArray {
        val parts = encoded.split('.')
        val flags = Base64.URL_SAFE or Base64.NO_WRAP or Base64.NO_PADDING
        val key: SecretKey
        val ivText: String
        val bodyText: String
        when {
            parts.size == 3 && parts[0] == "v1" -> {
                key = secretKey()
                ivText = parts[1]
                bodyText = parts[2]
            }
            parts.size == 4 && parts[0] == "rsa1" -> {
                val keyStore = KeyStore.getInstance(ANDROID_KEY_STORE).apply { load(null) }
                val privateKey = keyStore.getKey(keyAlias() + RSA_KEY_SUFFIX, null) as? java.security.PrivateKey
                    ?: throw IllegalStateException("Keystore wrapping key is unavailable")
                val wrapper = Cipher.getInstance("RSA/ECB/PKCS1Padding")
                wrapper.init(Cipher.DECRYPT_MODE, privateKey)
                key = SecretKeySpec(wrapper.doFinal(Base64.decode(parts[1], flags)), "AES")
                ivText = parts[2]
                bodyText = parts[3]
            }
            else -> throw IllegalStateException("Stored preferences have an invalid encryption envelope")
        }
        val iv = Base64.decode(ivText, flags)
        require(iv.size == IV_BYTES) { "Stored preferences have an invalid IV" }
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(GCM_TAG_BITS, iv))
        cipher.updateAAD(storeName.toByteArray(StandardCharsets.UTF_8))
        return cipher.doFinal(Base64.decode(bodyText, flags))
    }

    private fun readEncryptedPayload(): MutableMap<String, Any> {
        val encoded = disk.getString(PAYLOAD_KEY, null) ?: return mutableMapOf()
        return try {
            decodeValues(JSONObject(String(decrypt(encoded), StandardCharsets.UTF_8)))
        } catch (error: Exception) {
            AppLog.e("KeystoreEncryptedPreferences", "Secure preferences could not be decrypted; refusing plaintext fallback", error)
            throw IllegalStateException("Secure preferences are unavailable", error)
        }
    }

    private fun decodeValues(payload: JSONObject): MutableMap<String, Any> {
        val result = mutableMapOf<String, Any>()
        val keys = payload.keys()
        while (keys.hasNext()) {
            val key = keys.next()
            val entry = payload.optJSONObject(key) ?: continue
            when (entry.optString("type")) {
                "string" -> entry.optString("value").takeUnless { it == JSONObject.NULL }?.let { result[key] = it }
                "int" -> result[key] = entry.optInt("value")
                "long" -> result[key] = entry.optLong("value")
                "float" -> result[key] = entry.optDouble("value").toFloat()
                "boolean" -> result[key] = entry.optBoolean("value")
                "string_set" -> {
                    val array = entry.optJSONArray("value") ?: JSONArray()
                    result[key] = (0 until array.length()).mapNotNull { array.optString(it, null) }.toSet()
                }
            }
        }
        return result
    }

    private fun encodeValues(source: Map<String, Any>): ByteArray {
        val payload = JSONObject()
        source.forEach { (key, value) ->
            val entry = JSONObject()
            when (value) {
                is String -> entry.put("type", "string").put("value", value)
                is Int -> entry.put("type", "int").put("value", value)
                is Long -> entry.put("type", "long").put("value", value)
                is Float -> entry.put("type", "float").put("value", value.toDouble())
                is Boolean -> entry.put("type", "boolean").put("value", value)
                is Set<*> -> entry.put("type", "string_set").put("value", JSONArray(value.filterIsInstance<String>()))
                else -> return@forEach
            }
            payload.put(key, entry)
        }
        return payload.toString().toByteArray(StandardCharsets.UTF_8)
    }

    override fun getAll(): MutableMap<String, *> = synchronized(lock) { deepCopy(values) }
    override fun getString(key: String, defValue: String?): String? = synchronized(lock) { values[key] as? String ?: defValue }
    override fun getStringSet(key: String, defValues: MutableSet<String>?): MutableSet<String>? = synchronized(lock) {
        (values[key] as? Set<*>)?.filterIsInstance<String>()?.toMutableSet() ?: defValues?.toMutableSet()
    }
    override fun getInt(key: String, defValue: Int): Int = synchronized(lock) { values[key] as? Int ?: defValue }
    override fun getLong(key: String, defValue: Long): Long = synchronized(lock) { values[key] as? Long ?: defValue }
    override fun getFloat(key: String, defValue: Float): Float = synchronized(lock) { values[key] as? Float ?: defValue }
    override fun getBoolean(key: String, defValue: Boolean): Boolean = synchronized(lock) { values[key] as? Boolean ?: defValue }
    override fun contains(key: String): Boolean = synchronized(lock) { values.containsKey(key) }
    override fun edit(): SharedPreferences.Editor = SecureEditor()
    override fun registerOnSharedPreferenceChangeListener(listener: SharedPreferences.OnSharedPreferenceChangeListener?) {
        if (listener != null) listeners.add(listener)
    }

    override fun unregisterOnSharedPreferenceChangeListener(listener: SharedPreferences.OnSharedPreferenceChangeListener?) {
        if (listener != null) listeners.remove(listener)
    }

    private fun deepCopy(input: Map<String, Any>): MutableMap<String, Any> = input.mapValuesTo(mutableMapOf()) { (_, value) ->
        if (value is Set<*>) value.filterIsInstance<String>().toMutableSet() else value
    }

    private inner class SecureEditor : SharedPreferences.Editor {
        private val pending = linkedMapOf<String, Any?>()
        private var clearAll = false

        override fun putString(key: String, value: String?): SharedPreferences.Editor = set(key, value)
        override fun putStringSet(key: String, values: MutableSet<String>?): SharedPreferences.Editor = set(key, values?.toSet())
        override fun putInt(key: String, value: Int): SharedPreferences.Editor = set(key, value)
        override fun putLong(key: String, value: Long): SharedPreferences.Editor = set(key, value)
        override fun putFloat(key: String, value: Float): SharedPreferences.Editor = set(key, value)
        override fun putBoolean(key: String, value: Boolean): SharedPreferences.Editor = set(key, value)
        override fun remove(key: String): SharedPreferences.Editor = set(key, null)
        override fun clear(): SharedPreferences.Editor = apply { clearAll = true }

        private fun set(key: String, value: Any?): SharedPreferences.Editor = apply { pending[key] = value }

        override fun commit(): Boolean {
            val changed: Set<String>
            synchronized(lock) {
                val next = if (clearAll) mutableMapOf() else deepCopy(values)
                pending.forEach { (key, value) -> if (value == null) next.remove(key) else next[key] = value }
                val encrypted = crypt(encodeValues(next))
                if (!disk.edit().putString(PAYLOAD_KEY, encrypted).commit()) return false
                changed = (values.keys + next.keys).filterTo(mutableSetOf()) { values[it] != next[it] }
                values = next
            }
            changed.forEach { key -> listeners.forEach { it.onSharedPreferenceChanged(this@KeystoreEncryptedPreferences, key) } }
            pending.clear()
            clearAll = false
            return true
        }

        override fun apply() {
            val changed: Set<String>
            synchronized(lock) {
                val next = if (clearAll) mutableMapOf() else deepCopy(values)
                pending.forEach { (key, value) -> if (value == null) next.remove(key) else next[key] = value }
                val encrypted = crypt(encodeValues(next))
                changed = (values.keys + next.keys).filterTo(mutableSetOf()) { values[it] != next[it] }
                values = next
                disk.edit().putString(PAYLOAD_KEY, encrypted).apply()
            }
            changed.forEach { key -> listeners.forEach { it.onSharedPreferenceChanged(this@KeystoreEncryptedPreferences, key) } }
            pending.clear()
            clearAll = false
        }
    }
}
